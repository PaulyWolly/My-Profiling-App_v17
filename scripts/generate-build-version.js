/**
 * Writes src/environments/build-version.ts on each npm start / npm run build.
 * Timestamp = when the app was built/started (not last git commit).
 * Appends * when you have uncommitted local changes.
 */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

function isGitDirty() {
  try {
    const status = execSync('git status --porcelain', { encoding: 'utf8', stdio: ['pipe', 'pipe', 'ignore'] }).trim();
    return status.length > 0;
  } catch (_) {
    return false;
  }
}

function getShortHash() {
  try {
    return execSync('git rev-parse --short HEAD', { encoding: 'utf8', stdio: ['pipe', 'pipe', 'ignore'] }).trim();
  } catch (_) {
    return '';
  }
}

function formatVersionLabel(date, dirty, hash) {
  const month = date.getMonth() + 1;
  const day = date.getDate();
  const year = date.getFullYear();
  const hour = date.getHours();
  const minute = String(date.getMinutes()).padStart(2, '0');
  let label = `ver ${month}.${day}.${year}.${hour}:${minute}`;
  if (hash) {
    label += ` ${hash}`;
  }
  if (dirty) {
    label += '*';
  }
  return label;
}

const outPath = path.join(__dirname, '..', 'src', 'environments', 'build-version.ts');
const dirty = isGitDirty();
const hash = getShortHash();
const label = formatVersionLabel(new Date(), dirty, hash);
const contents = `// Auto-generated by scripts/generate-build-version.js — do not edit manually
export const buildVersion = '${label}';
`;

fs.writeFileSync(outPath, contents, 'utf8');
console.log('[generate-build-version]', label, dirty ? '(uncommitted changes)' : '');
